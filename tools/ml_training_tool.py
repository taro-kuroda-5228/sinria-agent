def _json(data: Dict[str, Any]) -> str:
    return json.dumps(data, ensure_ascii=False, indent=2)


def _package_available(import_name: str) -> bool:
    return importlib.util.find_spec(import_name) is not None


def _detect_torch() -> Dict[str, Any]:
    if not _package_available("torch"):
        return {"installed": False}
    try:
        import torch  # type: ignore

        return {
            "installed": True,
            "version": getattr(torch, "__version__", None),
            "cuda_available": bool(torch.cuda.is_available()),
            "cuda_device_count": int(torch.cuda.device_count()) if torch.cuda.is_available() else 0,
            "mps_available": bool(
                getattr(torch.backends, "mps", None) is not None
                and torch.backends.mps.is_available()
            ),
        }
    except Exception as exc:  # pragma: no cover - defensive environment probe
        return {"installed": True, "probe_error": str(exc)}


def _env_check() -> str:
    packages = {
        package: _package_available(import_name)
        for package, import_name in _PACKAGE_IMPORTS.items()
    }
    missing_core = [
        name for name in ["accelerate", "datasets", "peft", "torch", "transformers", "trl"]
        if not packages.get(name)
    ]
    result = {
        "success": True,
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "commands": {
            "git": bool(shutil.which("git")),
            "hf": bool(shutil.which("hf")),
            "wandb": bool(shutil.which("wandb")),
        },
        "packages": packages,
        "torch": _detect_torch(),
        "credentials": {
            "HF_TOKEN_set": bool(os.getenv("HF_TOKEN") or os.getenv("HUGGINGFACE_HUB_TOKEN")),
            "WANDB_API_KEY_set": bool(os.getenv("WANDB_API_KEY")),
        },
        "ready_for_local_lora": not missing_core,
        "missing_core_packages": missing_core,
        "install_command": "python -m pip install -U " + " ".join(_DEFAULT_REQUIREMENTS.split()),
        "notes": [
            "bitsandbytes is optional and mainly useful on CUDA GPUs; Apple Silicon can use MPS without it.",
            "Use terminal(background=true, notify_on_complete=true) for real training runs so progress remains observable.",
        ],
    }
    return _json(result)


def _safe_project_dir(project_dir: str) -> Path:
    if not project_dir or not project_dir.strip():
        raise ValueError("project_dir is required")
    path = Path(project_dir).expanduser()
    if not path.is_absolute():
        path = Path.cwd() / path
    return path.resolve()


def _write_file(path: Path, content: str, overwrite: bool) -> None:
    if path.exists() and not overwrite:
        raise FileExistsError(f"Refusing to overwrite existing file: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _scaffold_lora(args: Dict[str, Any]) -> str:
    project_dir = _safe_project_dir(str(args.get("project_dir") or "ml-finetune"))
    overwrite = bool(args.get("overwrite", False))
    base_model = str(args.get("base_model") or "Qwen/Qwen2.5-0.5B-Instruct")
    text_field = str(args.get("text_field") or "text")
    output_dir = str(args.get("output_dir") or "outputs/lora")
    max_steps = int(args.get("max_steps") or 100)
    batch_size = int(args.get("batch_size") or 1)
    grad_accum = int(args.get("grad_accum") or 8)
    learning_rate = float(args.get("learning_rate") or 2e-4)

    if project_dir.exists() and any(project_dir.iterdir()) and not overwrite:
        raise FileExistsError(
            f"Project directory is not empty: {project_dir}. Set overwrite=true to replace generated files."
        )

    _write_file(project_dir / "requirements.txt", _DEFAULT_REQUIREMENTS, overwrite)
    _write_file(project_dir / "train_lora.py", _TRAIN_SCRIPT, overwrite)
    _write_file(project_dir / "data" / "sample.jsonl", _SAMPLE_DATASET, overwrite)
    _write_file(
        project_dir / "README.md",
        _README_TEMPLATE.format(
            base_model=base_model,
            text_field=text_field,
            output_dir=output_dir,
            max_steps=max_steps,
            batch_size=batch_size,
            grad_accum=grad_accum,
            learning_rate=learning_rate,
        ),
        overwrite,
    )

    project_dir_arg = shlex.quote(str(project_dir))
    base_model_arg = shlex.quote(base_model)
    text_field_arg = shlex.quote(text_field)
    output_dir_arg = shlex.quote(output_dir)
    max_steps_arg = shlex.quote(str(max_steps))
    batch_size_arg = shlex.quote(str(batch_size))
    grad_accum_arg = shlex.quote(str(grad_accum))
    learning_rate_arg = shlex.quote(str(learning_rate))

    run_command = (
        f"cd {project_dir_arg} && "
        "python train_lora.py "
        f"--base-model {base_model_arg} "
        "--dataset data/sample.jsonl "
        f"--text-field {text_field_arg} "
        f"--output-dir {output_dir_arg} "
        f"--max-steps {max_steps_arg} "
        f"--batch-size {batch_size_arg} "
        f"--grad-accum {grad_accum_arg} "
        f"--learning-rate {learning_rate_arg}"
    )
    install_command = (
        f"cd {project_dir_arg} && python3 -m venv .venv && "
        "source .venv/bin/activate && python -m pip install --upgrade pip && "
        "python -m pip install -r requirements.txt"
    )
    return _json(
        {
            "success": True,
            "project_dir": str(project_dir),
            "files": [
                "requirements.txt",
                "train_lora.py",
                "data/sample.jsonl",
                "README.md",
            ],
            "install_command": install_command,
            "run_command": run_command,
            "recommended_terminal_usage": {
                "install": "terminal(command=install_command, timeout=600)",
                "train": "terminal(command='source .venv/bin/activate && ...', background=true, notify_on_complete=true)",
            },
        }
    )


def _validate_dataset(dataset_path: str, text_field: str = "text", max_rows: int = 5) -> str:
    if not dataset_path:
        raise ValueError("dataset_path is required")
    path = Path(dataset_path).expanduser()
    if not path.exists():
        raise FileNotFoundError(f"Dataset path not found: {path}")
    rows = []
    if path.suffix.lower() in {".jsonl", ".json"}:
        with path.open("r", encoding="utf-8") as fh:
            for idx, line in enumerate(fh, start=1):
                if not line.strip():
                    continue
                obj = json.loads(line)
                rows.append({"line": idx, "has_text_field": text_field in obj, "keys": sorted(obj.keys())})
                if len(rows) >= max_rows:
                    break
    else:
        return _json({"success": False, "error": f"Unsupported validation extension: {path.suffix}"})
    return _json(
        {
            "success": True,
            "dataset_path": str(path.resolve()),
            "text_field": text_field,
            "sampled_rows": rows,
            "valid": bool(rows) and all(row["has_text_field"] for row in rows),
        }
    )


def _plan(args: Dict[str, Any]) -> str:
    base_model = str(args.get("base_model") or "Qwen/Qwen2.5-0.5B-Instruct")
    return _json(
        {
            "success": True,
            "recommended_flow": [
                "Run action='env_check' to inspect packages, GPU/MPS/CUDA, and credentials.",
                "Run action='scaffold_lora' to create a reproducible LoRA fine-tuning workspace.",
                "Replace data/sample.jsonl with a reviewed dataset. For medical/confidential data, confirm approved storage and compute first.",
                "Install dependencies in the generated venv.",
                "Launch training with terminal(background=true, notify_on_complete=true), then monitor via process.poll/log.",
                "Optionally upload adapters to Hugging Face Hub only after privacy and licensing checks.",
            ],
            "base_model": base_model,
            "local_compute_notes": [
                "Small smoke tests can run on CPU/MPS; practical LLM fine-tuning usually needs a CUDA GPU or remote runner.",
                "Use LoRA adapters first; full fine-tuning is much more expensive and riskier.",
            ],
        }
    )


def ml_training(action: str, **kwargs: Any) -> str:
    """Dispatch ML training helper actions."""
    try:
        action = (action or "env_check").strip().lower()
        if action == "env_check":
            return _env_check()
        if action == "plan":
            return _plan(kwargs)
        if action == "scaffold_lora":
            return _scaffold_lora(kwargs)
        if action == "validate_dataset":
            return _validate_dataset(
                dataset_path=str(kwargs.get("dataset_path") or ""),
                text_field=str(kwargs.get("text_field") or "text"),
                max_rows=int(kwargs.get("max_rows") or 5),
            )
        return _json({"success": False, "error": f"Unknown action: {action}"})
    except Exception as exc:
        return _json({"success": False, "error": str(exc), "action": action})


