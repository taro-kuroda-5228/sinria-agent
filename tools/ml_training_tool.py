_TRAIN_SCRIPT = r'''#!/usr/bin/env python3
"""LoRA/QLoRA supervised fine-tuning entrypoint generated by Sinria."""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import torch
from datasets import load_dataset
from peft import LoraConfig
from transformers import AutoModelForCausalLM, AutoTokenizer, TrainingArguments
from trl import SFTTrainer


def _best_dtype():
    if torch.cuda.is_available():
        return torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16
    if getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
        return torch.float16
    return torch.float32


def main() -> None:
    parser = argparse.ArgumentParser(description="LoRA/QLoRA SFT training")
    parser.add_argument("--base-model", required=True)
    parser.add_argument("--dataset", required=True, help="JSONL/JSON/CSV path or Hugging Face dataset id")
    parser.add_argument("--text-field", default="text")
    parser.add_argument("--output-dir", default="./outputs/lora")
    parser.add_argument("--max-seq-length", type=int, default=2048)
    parser.add_argument("--max-steps", type=int, default=100)
    parser.add_argument("--epochs", type=float, default=None)
    parser.add_argument("--learning-rate", type=float, default=2e-4)
    parser.add_argument("--batch-size", type=int, default=1)
    parser.add_argument("--grad-accum", type=int, default=8)
    parser.add_argument("--lora-r", type=int, default=16)
    parser.add_argument("--lora-alpha", type=int, default=32)
    parser.add_argument("--lora-dropout", type=float, default=0.05)
    parser.add_argument("--report-to", default="none", choices=["none", "wandb"])
    parser.add_argument("--push-to-hub", action="store_true")
    parser.add_argument("--hub-model-id", default=None)
    args = parser.parse_args()

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    if Path(args.dataset).exists():
        suffix = Path(args.dataset).suffix.lower()
        if suffix in {".jsonl", ".json"}:
            dataset = load_dataset("json", data_files=str(args.dataset), split="train")
        elif suffix == ".csv":
            dataset = load_dataset("csv", data_files=str(args.dataset), split="train")
        else:
            raise ValueError(f"Unsupported local dataset extension: {suffix}")
    else:
        dataset = load_dataset(args.dataset, split="train")

    tokenizer = AutoTokenizer.from_pretrained(args.base_model, use_fast=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        args.base_model,
        torch_dtype=_best_dtype(),
        device_map="auto" if torch.cuda.is_available() else None,
    )

    peft_config = LoraConfig(
        r=args.lora_r,
        lora_alpha=args.lora_alpha,
        lora_dropout=args.lora_dropout,
        bias="none",
        task_type="CAUSAL_LM",
        target_modules="all-linear",
    )

    training_args = TrainingArguments(
        output_dir=str(output_dir),
        max_steps=args.max_steps if args.epochs is None else -1,
        num_train_epochs=args.epochs if args.epochs is not None else 1,
        per_device_train_batch_size=args.batch_size,
        gradient_accumulation_steps=args.grad_accum,
        learning_rate=args.learning_rate,
        logging_steps=5,
        save_steps=50,
        save_total_limit=3,
        bf16=torch.cuda.is_available() and torch.cuda.is_bf16_supported(),
        fp16=(torch.cuda.is_available() and not torch.cuda.is_bf16_supported()) or (
            getattr(torch.backends, "mps", None) and torch.backends.mps.is_available()
        ),
        report_to=[] if args.report_to == "none" else [args.report_to],
        push_to_hub=args.push_to_hub,
        hub_model_id=args.hub_model_id,
    )

    trainer = SFTTrainer(
        model=model,
        tokenizer=tokenizer,
        train_dataset=dataset,
        dataset_text_field=args.text_field,
        max_seq_length=args.max_seq_length,
        peft_config=peft_config,
        args=training_args,
    )
    trainer.train()
    trainer.save_model(str(output_dir))
    tokenizer.save_pretrained(str(output_dir))
    if args.push_to_hub:
        trainer.push_to_hub()


if __name__ == "__main__":
    main()
'''

